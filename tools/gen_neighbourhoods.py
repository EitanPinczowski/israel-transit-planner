#!/usr/bin/env python
"""Generate the bundled neighbourhood table for place search (Phase 10 D2).

    python tools/gen_neighbourhoods.py

Reads tools/neighbourhoods_seed.tsv (hand-checked) and writes
core/src/main/kotlin/il/transit/core/search/NeighbourhoodsData.kt. No requests and no
coordinates of our own: a neighbourhood only names its town(s), and every town must be in
tools/towns_seed.tsv, whose centre the search then uses. Fails on an unknown town or a name
listed twice.
"""
from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SEED = ROOT / "tools/neighbourhoods_seed.tsv"
TOWNS = ROOT / "tools/towns_seed.tsv"
OUT = ROOT / "core/src/main/kotlin/il/transit/core/search/NeighbourhoodsData.kt"


def rows(path: pathlib.Path):
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip() and not line.startswith("#"):
            yield line.split("\t")


def norm(s: str) -> str:
    """PlaceSearch.normalize: lower case, no quote marks, dashes as spaces."""
    s = "".join(c for c in s.lower() if c not in "\"'״׳`")
    return " ".join(s.replace("-", " ").replace("־", " ").replace("–", " ").split())


def kt(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    towns = {n for r in rows(TOWNS) for n in r[0].split("|") + r[1].split("|")}
    out, seen, errors = [], set(), []
    for r in rows(SEED):
        he, en, town = (r + ["", ""])[:3]
        names = [n for n in he.split("|") + en.split("|") if n]
        for t in town.split("|"):
            if t not in towns:
                errors.append(f"{names[0]}: unknown town {t!r} (add it to towns_seed.tsv)")
        for n in names:
            if norm(n) in seen:
                errors.append(f"{n}: listed twice (the same name without its marks)")
            seen.add(norm(n))
        out.append(f"        Neighbourhood(listOf({', '.join(kt(n) for n in names)}), listOf({', '.join(kt(t) for t in town.split('|'))})),")
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    OUT.write_text(
        "package il.transit.core.search\n\n"
        "// GENERATED by tools/gen_neighbourhoods.py from tools/neighbourhoods_seed.tsv — do not edit by hand.\n"
        f"// {len(out)} neighbourhoods.\n"
        "internal object NeighbourhoodsData {\n    val ALL: List<Neighbourhood> = listOf(\n" + "\n".join(out) + "\n    )\n}\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT.relative_to(ROOT)}: {len(out)} neighbourhoods")
    return 0


if __name__ == "__main__":
    sys.exit(main())
