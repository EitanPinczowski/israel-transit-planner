package il.transit.core.search

import il.transit.core.geo.Geo
import il.transit.core.geo.LatLon

/** A neighbourhood: every spelling people type, and the town(s) it is in (a name in two towns lists both). */
data class Neighbourhood(val names: List<String>, val townNames: List<String>) {
    /** Its towns, from the town table ([Towns]): no coordinates of our own. */
    val towns: List<Town> get() = townNames.mapNotNull(Towns::named)
}

/**
 * One row per town for a neighbourhood name in several ("רמות" → "רמות, ירושלים", "רמות, באר שבע"):
 * tapping it searches [query], which names the town (owner, 2026-10-12: 0 requests until the tap).
 */
data class TownChoice(val town: Town, val query: String)

/**
 * The bundled neighbourhood table (`NeighbourhoodsData`, generated by
 * `tools/gen_neighbourhoods.py`, Phase 10 D2): "רמת אביב" is in Tel Aviv, "רמות" in Jerusalem and
 * in Be'er Sheva. A search that names one and no town searches near its town's centre. 0 requests.
 */
object Neighbourhoods {
    val ALL: List<Neighbourhood> get() = NeighbourhoodsData.ALL

    private val byName: Map<String, Neighbourhood> by lazy {
        ALL.flatMap { n -> n.names.map { PlaceSearch.normalize(it) to n } }.toMap()
    }
    private val longest: Int by lazy { byName.keys.maxOf { it.split(' ').size } }

    /** A word before the name that makes it a street ("רחוב רמות", "דרך בית לחם"). */
    private val STREET_WORDS = setOf("רחוב", "רח", "שדרות", "שד", "שדרת", "דרך", "סמטת", "סמטה", "כיכר", "ככר", "st", "street", "rd", "road")

    fun named(name: String): Neighbourhood? = byName[PlaceSearch.normalize(name)]

    /**
     * The neighbourhood [query] names, if any: the longest run of words that is one, not after a
     * street word, and not a name followed only by a house number ("גילה 5" is a street). Empty
     * when none. Read from the text as typed ("רחוב" is dropped before the search). The caller asks only
     * when no town was typed.
     */
    fun typedIn(query: String): List<Neighbourhood> {
        val words = PlaceSearch.normalize(query).replace(",", " ").split(' ').filter { it.isNotEmpty() }
        for (k in minOf(longest, words.size) downTo 1) {
            for (start in 0..words.size - k) {
                val n = byName[words.subList(start, start + k).joinToString(" ")] ?: continue
                if (words.getOrNull(start - 1) in STREET_WORDS) continue
                val after = words.drop(start + k)
                if (start == 0 && after.isNotEmpty() && after.all { it.first().isDigit() }) continue
                return listOf(n)
            }
        }
        return emptyList()
    }

    /** [n]'s towns, the one nearest [near] first ("nearby first"); the table's order without a location. */
    fun townsByDistance(n: Neighbourhood, near: LatLon?): List<Town> =
        if (near == null) n.towns else n.towns.sortedBy { Geo.distanceM(it.centre, near) }
}
